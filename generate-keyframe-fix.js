/**
 * generate-keyframe-fix.js
 * ---------------------------------------------------------------
 * If seeking during playback shows a momentarily frozen video frame
 * while audio keeps playing, it's almost always because the source
 * file doesn't have a keyframe exactly at (or very near) every
 * segment cut point — the decoder has to wait for the next keyframe
 * before it can render a correct frame after a seek. Audio has no
 * such restriction, hence the desync illusion.
 *
 * This script reads SegmentMap.js and prints an ffmpeg command that
 * re-encodes your file with a forced keyframe at every single
 * branch-point timestamp, so every possible cut in the film lands
 * exactly on a keyframe.
 *
 * Usage:
 *   node generate-keyframe-fix.js > reencode.sh
 *   bash reencode.sh   # edit INPUT/OUTPUT paths inside first
 *
 * Note: this does a full re-encode (not stream copy), because
 * forcing keyframes at arbitrary timestamps requires re-encoding the
 * video stream. Expect it to take a while depending on your hardware
 * and the codec/preset you choose below. Audio can be stream-copied.
 */
require('./segment-map.js');

const times = new Set();
for (const id in SegmentMap.segments) {
  times.add(SegmentMap.segments[id].startTimeMs);
}
const sorted = [...times].sort((a, b) => a - b).map(ms => (ms / 1000).toFixed(3));

console.log(`#!/usr/bin/env bash
# Auto-generated by generate-keyframe-fix.js
# EDIT THESE TWO PATHS:
INPUT="bandersnatch-original.mkv"
OUTPUT="bandersnatch-keyframed.mkv"

ffmpeg -i "$INPUT" \\
  -force_key_frames "${sorted.join(',')}" \\
  -c:v libx264 -preset medium -crf 18 \\
  -c:a copy \\
  "$OUTPUT"

echo "Done. Point Jellyfin at $OUTPUT instead of the original file."
`);
